"""Build demo/data/collection.json from a snapshot of the existing site's catalogue.

The existing site (https://tartary.vercel.app) reads its catalogue from a Railway API and its
images from S3, all in Alexia's personal accounts. A snapshot of the API is kept outside this
repository; this script turns it into one file the demo can serve itself, and copies the
thumbnails into demo/img/thumbs so the front page does not load them from her bucket on every
visit. The deep-zoom tiles still come from her bucket.

    python scripts/build_collection.py ../site-snapshot

Records are copied as they are, apart from: sources recorded as "0" are dropped, a missing
title becomes null (the page shows "Untitled"), and the list is sorted by year.
Thumbnails already in demo/img/thumbs are kept; delete one to fetch it again.
"""
import io
import json
import re
import sys
import urllib.parse
import urllib.request
from pathlib import Path

from PIL import Image

# Map ids (the existing site's map_id) to leave out of the public demo, e.g. the maps whose
# rights are not yet cleared. Prof. Caboara was asked which ones on 29 Oct 2026.
HIDDEN = []

DEMO = Path(__file__).resolve().parent.parent / "demo"
OUT = DEMO / "data" / "collection.json"
THUMBS = DEMO / "img" / "thumbs"
THUMB_MAX = 400  # px, longest side; the grid shows them at about 170 px wide


def fetch_thumb(url, n):
    path = THUMBS / f"{n}.jpg"
    if not path.exists():
        parts = urllib.parse.urlsplit(url)
        safe = parts._replace(path=urllib.parse.quote(parts.path, safe="/%")).geturl()  # some paths are already escaped
        with urllib.request.urlopen(safe, timeout=60) as r:
            img = Image.open(io.BytesIO(r.read())).convert("RGB")
        img.thumbnail((THUMB_MAX, THUMB_MAX), Image.LANCZOS)
        img.save(path, quality=80, optimize=True)
    return f"img/thumbs/{n}.jpg"


def main(snapshot):
    snapshot = Path(snapshot)
    THUMBS.mkdir(parents=True, exist_ok=True)
    listing = json.loads((snapshot / "maps.json").read_text(encoding="utf-8"))
    maps = []
    for row in listing:
        if row["map_id"] in HIDDEN:
            continue
        record = json.loads((snapshot / "maps" / f"{row['map_id']}.json").read_text(encoding="utf-8"))
        year = (row["year_text"] or "").strip()
        maps.append({
            "n": row["map_id"],
            "year": year,
            "title": (row["title"] or "").strip() or None,
            "authors": [a.strip() for a in row["authors"] or []],
            "sources": [s.strip() for s in row["sources"] or [] if s.strip() not in ("", "0")],
            "thumb": fetch_thumb(row["thumb_path"], row["map_id"]),
            "dzi": record["dzi_url"],
        })
    maps.sort(key=lambda m: (int(re.match(r"\d{4}", m["year"])[0]) if re.match(r"\d{4}", m["year"]) else 9999, m["n"]))
    out = {
        "_comment": "Generated by scripts/build_collection.py from a snapshot of the TARTARY Project catalogue. Do not edit by hand.",
        "source": "https://tartary.vercel.app",
        "snapshot": re.search(r"Taken (\d{4}-\d{2}-\d{2})", (snapshot / "README.md").read_text(encoding="utf-8"))[1],
        "hidden": len(HIDDEN),
        "maps": maps,
    }
    OUT.write_text(json.dumps(out, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"{len(maps)} maps -> {OUT}")


if __name__ == "__main__":
    main(sys.argv[1])
