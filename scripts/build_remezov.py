"""Build a private review copy of the Remezov ethnographic map from the transcription test's output.

    python scripts/build_remezov.py ../map-test/output
    python scripts/make_dzi.py ../map-test/sources/remezov/remezov_full.jpg demo/private/remezov-1673/tiles/remezov-1673

Writes demo/private/remezov-1673/remezov-1673.json and demo/private/catalogue.json. demo/private/ is
in .gitignore: the image rights for this scan are not cleared ("I have no rights to it", project
notes), so it is for local review only and never reaches GitHub Pages.

The texts are the two agents' output as scored in map-test/results.md. Ids are the agent's side and
its position in that agent's output (l00, r17, ...), so a corrections file stays valid when this is
rebuilt; the numbers on the map cannot serve as ids (93 appears eleven times). The agents gave only
the centre of each label (to about 40 px), so every box here is a default size around that centre,
marked "region_approx": the reviewer redraws it.
"""
import json
import re
import sys
from datetime import date
from pathlib import Path

DEMO = Path(__file__).resolve().parent.parent / "demo"
OUT = DEMO / "private" / "remezov-1673"
WIDTH, HEIGHT = 13016, 8712
CYRILLIC = re.compile(r"[Ѐ-ԯꙀ-ꚟ]")


def incipit(text, n=46):
    return text if len(text) <= n + 2 else text[:n].rsplit(" ", 1)[0] + " …"


def category(original):
    if not CYRILLIC.search(original):
        return "numeral"
    return "inscription" if original.count(" | ") >= 3 and len(original) > 60 else "toponym"


def default_box(label):
    x, y = label["centre"]
    lines = label["original"].split(" | ")
    if category(label["original"]) == "numeral":
        w = h = 240
    else:
        w = min(1600, max(260, 70 * max(len(l) for l in lines)))
        h = min(1200, 150 * len(lines) + 40)
    x0, y0 = max(0, int(x - w / 2)), max(0, int(y - h / 2))
    return {"x": x0, "y": y0, "w": min(w, WIDTH - x0), "h": min(h, HEIGHT - y0)}


def main(test_output):
    test_output = Path(test_output)
    annotations = []
    for side in ("left", "right"):
        labels = json.loads((test_output / f"remezov_map_{side}.json").read_text(encoding="utf-8"))["labels"]
        for i, lab in enumerate(labels):
            modern = re.sub(r"^\s*\d+[.,]?\s*", "", lab["modern"]).strip() or lab["modern"]
            english = re.sub(r"^\s*\d+(\s*\[\?\])?[.,]?\s*", "", lab["translation_en"]).strip() or lab["translation_en"]
            cat = category(lab["original"])
            annotations.append({
                "id": f"{side[0]}{i:02d}",
                "view": "map",
                "category": cat,
                "tour": cat != "numeral",
                "confidence": lab["confidence"],
                "number": lab.get("number"),
                "label": {"ru": incipit(modern), "en": incipit(english)},
                "region": default_box(lab),
                "region_approx": True,
                "text": {
                    "lang": "ru",
                    "original": lab["original"].replace(" | ", "\n"),
                    "expanded": lab["modern"],
                    "translation": lab["translation_en"],
                    "commentary": (lab.get("note") or "").strip(),
                    "source": [f"Read by Claude Opus 5.5 on 29 Oct 2026 from crops {', '.join(lab.get('crops') or [])} of the Rumsey scan ({side} page agent)."],
                },
            })
    out = {
        "_comment": "PRIVATE. Generated by scripts/build_remezov.py; image rights not cleared, do not publish.",
        "id": "remezov-1673",
        "built": date.today().isoformat(),
        "title": {"en": "Ethnographical map of Siberia (Remezov atlas, sheet 23)"},
        "short": {"en": "Remezov, ethnographic map (private)"},
        "creator": "Remezov atlas (Chertezhnaya kniga Sibiri), after a map drawn at Tobolsk in 1673",
        "date": "This copy c. 1699–1701",
        "notice": "Private review copy: image rights not cleared, not for publication. Machine transcription and translation (Claude Opus 5.5, 29 Oct 2026); boxes are approximate.",
        "catalogue": {
            "repository": "Russian State Library, f. 256 № 346, l. 27; scan by the David Rumsey Map Collection",
            "reference": "Rumsey list no. 15138.000; Baddeley, Russia, Mongolia, China (1919), pp. cxxxvi–cxlii",
            "credit": "David Rumsey Map Collection (rights not cleared for this project)",
        },
        "description": "The map Baddeley called the Ethnographical Map of 1673: Siberia and its neighbours as coloured regions, each with a number and a name, south at the top. 113 labels were read by two AI agents that saw only the scan. Baddeley's English list of the numbered names agrees with 86 of his 94 entries; the misreadings found all sit in labels the model marked medium or low confidence.",
        "views": [{"id": "map", "label": {"en": "Map"}, "tileSource": "private/remezov-1673/tiles/remezov-1673.dzi",
                   "width": WIDTH, "height": HEIGHT}],
        "annotations": annotations,
    }
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "remezov-1673.json").write_text(json.dumps(out, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    (DEMO / "private" / "catalogue.json").write_text(json.dumps({
        "_comment": "Maps for local review only (demo/private is not published).",
        "maps": [{"id": "remezov-1673", "file": "private/remezov-1673/remezov-1673.json",
                  "title": out["title"], "short": out["short"]}],
    }, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"{len(annotations)} labels -> {OUT / 'remezov-1673.json'}")


if __name__ == "__main__":
    main(sys.argv[1])
